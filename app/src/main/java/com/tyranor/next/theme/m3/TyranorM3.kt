/**
 * 由应用设置「应用圆角调整」生成的 M3 形状阶梯。
 * 用户可调 5..50dp；以该值为 large 档，其余档按 M3 比例缩放并夹取到合理范围。
 */
fun tyranorShapes(radiusDp: Int): Shapes {
    val large = radiusDp.coerceIn(5, 50).dp
    return Shapes(
        extraSmall = RoundedCornerShape((large.value * 0.2f).dp),
        small = RoundedCornerShape((large.value * 0.45f).dp),
        medium = RoundedCornerShape((large.value * 0.7f).dp),
        large = RoundedCornerShape(large),
        extraLarge = RoundedCornerShape((large.value * 1.6f).dp),
    )
}
